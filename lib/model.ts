// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the 40 watchlist slugs (the floor,
// never the ceiling) plus every other pre-token protocol below the floor that is not a wrapped, staked
// or bridged product of a token that already trades. A protocol is pre-token when its record carries
// no token at all: no market cap, no CoinGecko id, no symbol. Live-token protocols are kept apart and
// shown with the market's own values, never mixed into the ranked board.
//
// Implied value is a comparable-multiple valuation, computed from the snapshot itself, never from a
// hand-written list of names:
//
//   multiple(category) = clamp((n * median(mcap/tvl of live protocols in the category)
//                          + 3 * global median) / (n + 3), 0.02, 2.0)
//   — but only when the category has at least 3 traded protocols behind its median. A thinner
//   category takes the global median instead: one small protocol's ratio (a $6M-TVL protocol with a
//   $2.6B market cap is 400x) must never set the multiple for a whole category.
//   growth    = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) * 0.6
//   maturity  = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   implied   = max(1, round(tvl_usd * multiple * growthMult * maturity))
//
// The category multiple is the median fully-diluted-value-per-TVL of the protocols in that category
// whose token already trades, shrunk toward the global median when the category has few comparables
// (three pseudo-observations at the global median). A category with no live protocol at all takes the
// global median. The same function scores every row; no protocol name is ever special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

